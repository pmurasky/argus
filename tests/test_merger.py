import json

from argus.merger import JsonMerger, MarkedBlockMerger

GENERATED_AGENTS = "<!-- Generated by argus -->\n\n# Engineering Standards\n\n## TDD\n\nCore rule."

GENERATED = json.dumps(
    {"$schema": "https://opencode.ai/config.json", "instructions": ["AGENTS.md"]}
)


def merge(existing: str, generated: str = GENERATED) -> dict:
    result = JsonMerger().merge(existing, generated)
    assert result is not None
    return json.loads(result)


def test_preserves_unknown_top_level_keys():
    existing = json.dumps({"default_agent": "standards-build", "plugin": ["context-mode"]})
    merged = merge(existing)
    assert merged["default_agent"] == "standards-build"
    assert merged["plugin"] == ["context-mode"]


def test_updates_argus_owned_schema_key():
    existing = json.dumps({"$schema": "https://old.example/config.json"})
    merged = merge(existing)
    assert merged["$schema"] == "https://opencode.ai/config.json"


def test_deep_merges_mcp_block_preserving_foreign_servers():
    existing = json.dumps({"mcp": {"gsd": {"type": "local", "command": ["gsd"]}}})
    merged = merge(existing)
    assert merged["mcp"]["gsd"] == {"type": "local", "command": ["gsd"]}


def test_unions_instructions_with_existing_array():
    existing = json.dumps({"instructions": ["docs/AI_AGENT_WORKFLOW.md"]})
    merged = merge(existing)
    assert merged["instructions"] == ["docs/AI_AGENT_WORKFLOW.md", "AGENTS.md"]


def test_unions_instructions_with_existing_string():
    existing = json.dumps({"instructions": "CUSTOM.md"})
    merged = merge(existing)
    assert merged["instructions"] == ["CUSTOM.md", "AGENTS.md"]


def test_merge_is_idempotent():
    existing = json.dumps({"instructions": ["docs/x.md", "AGENTS.md"], "default_agent": "plan"})
    once = JsonMerger().merge(existing, GENERATED)
    assert once is not None
    twice = JsonMerger().merge(once, GENERATED)
    assert once == twice


def test_returns_none_for_invalid_json():
    assert JsonMerger().merge("{ not json", GENERATED) is None


def test_marked_merger_without_markers_returns_generated_unchanged():
    assert MarkedBlockMerger().merge("old content", GENERATED_AGENTS) == GENERATED_AGENTS


def test_marked_merger_preserves_foreign_block_at_end():
    existing = (
        GENERATED_AGENTS
        + "\n\n<!-- gortex:communities:start -->\n## Communities\nkeep me\n<!-- gortex:communities:end -->\n"
    )
    merged = MarkedBlockMerger().merge(existing, GENERATED_AGENTS)
    assert merged.startswith(GENERATED_AGENTS)
    assert merged.endswith("<!-- gortex:communities:end -->")


def test_marked_merger_preserves_multiple_blocks_in_order():
    existing = (
        "<!-- a:x:start -->first<!-- a:x:end -->"
        " middle "
        "<!-- b:y:start -->second<!-- b:y:end -->"
    )
    merged = MarkedBlockMerger().merge(existing, GENERATED_AGENTS)
    assert merged.index("first") < merged.index("second")


def test_marked_merger_ignores_unbalanced_markers():
    existing = GENERATED_AGENTS + "\n<!-- gortex:communities:start -->\norphan"
    assert MarkedBlockMerger().merge(existing, GENERATED_AGENTS) == GENERATED_AGENTS


def test_marked_merger_is_idempotent():
    existing = (
        GENERATED_AGENTS
        + "\n\n<!-- gortex:communities:start -->\nkeep\n<!-- gortex:communities:end -->"
    )
    once = MarkedBlockMerger().merge(existing, GENERATED_AGENTS)
    twice = MarkedBlockMerger().merge(once, GENERATED_AGENTS)
    assert once == twice
